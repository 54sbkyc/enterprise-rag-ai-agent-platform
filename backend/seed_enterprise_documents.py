def render_content(title, sections):
    lines = [f"?????{title}", ""]
    for index, (heading, body) in enumerate(sections, start=1):
        lines.extend([f"{index}. {heading}", body, ""])
    return "\n".join(lines).strip() + "\n"


def seed_documents():
    init_db()
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    created_docs = []
    with get_conn() as conn:
        admin = conn.execute("SELECT id FROM users WHERE username = 'admin'").fetchone()
        admin_id = admin["id"] if admin else None
        for title, filename, access_level, sections in DOCS:
            existing = conn.execute("SELECT id FROM documents WHERE filename = ?", (filename,)).fetchone()
            if existing:
                continue
            content = render_content(title, sections)
            created = utc_now()
            storage_name = f"{created.replace(':', '-').replace('+', 'Z')}_{filename}"
            storage_path = UPLOAD_DIR / storage_name
            storage_path.write_text(content, encoding="utf-8")
            chunks = chunk_text(content)
            chunk_index = build_chunk_index(chunks)
            cursor = conn.execute(
                """
                INSERT INTO documents(
                    title, filename, file_type, storage_path, access_level,
                    status, chunk_count, embedding_status, embedding_model, created_at
                )
                VALUES (?, ?, 'md', ?, ?, 'ready', ?, ?, ?, ?)
                """,
                (
                    title,
                    filename,
                    str(storage_path),
                    access_level,
                    len(chunks),
                    chunk_index.status,
                    chunk_index.model,
                    created,
                ),
            )
            doc_id = cursor.lastrowid
            for index, item in enumerate(chunk_index.items):
                conn.execute(
                    """
                    INSERT INTO chunks(
                        document_id, chunk_index, content, token_json,
                        embedding_json, embedding_model, content_hash, created_at
                    )
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        doc_id,
                        index,
                        item.content,
                        item.token_json,
                        json.dumps(item.embedding),
                        chunk_index.model if item.embedding else None,
                        item.content_hash,
                        created,
                    ),
                )
            conn.execute(
                """
                INSERT INTO audit_logs(user_id, action, target_type, target_id, detail, created_at)
                VALUES (?, 'seed_document_suite', 'document', ?, ?, ?)
                """,
                (
                    admin_id,
                    doc_id,
                    json.dumps({"title": title, "access_level": access_level, "chunk_count": len(chunks)}, ensure_ascii=False),
                    created,
                ),
            )
            created_docs.append({"id": doc_id, "title": title, "level": access_level, "chunks": len(chunks)})
    return created_docs


if __name__ == "__main__":
    docs = seed_documents()
    print(json.dumps({"created_count": len(docs), "created_docs": docs}, ensure_ascii=False, indent=2))
